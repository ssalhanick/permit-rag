/**
 * Returns overall coverage metrics
 */
export function getCoverageStats() {
  const activeJurisdictions = JURISDICTIONS.filter((j) => j.status === "active");
  const totalDocs = JURISDICTIONS.reduce((acc, j) => acc + j.documents.length, 0);
  const totalPages = JURISDICTIONS.reduce(
    (acc, j) => acc + j.documents.reduce((sum, d) => sum + (d.pages || 0), 0),
    0
  );
  const dfwCities = JURISDICTIONS.filter((j) => j.type === "municipal" && j.state === "Texas");

  return {
    totalJurisdictions: JURISDICTIONS.length,
    activeJurisdictionsCount: activeJurisdictions.length,
    dfwCitiesCount: dfwCities.length,
    totalDocuments: totalDocs,
    totalPagesIndexed: totalPages,
    totalPipelineJurisdictions: PIPELINE_JURISDICTIONS.length,
    categoriesCount: 8,
  };
}

/**
 * Find jurisdiction by ID
 */
export function getJurisdictionById(id) {
  if (!id) return null;
  const match = JURISDICTIONS.find((j) => j.id.toLowerCase() === id.toLowerCase());
  if (match) return match;
  return PIPELINE_JURISDICTIONS.find((j) => j.id.toLowerCase() === id.toLowerCase()) || null;
}

/**
 * Returns all documents flattened with jurisdiction metadata
 */
export function getAllFlattenedDocuments() {
  const docs = [];
  JURISDICTIONS.forEach((j) => {
    j.documents.forEach((d) => {
      docs.push({
        ...d,
        jurisdictionId: j.id,
        jurisdictionName: j.name,
        jurisdictionType: j.type,
        jurisdictionState: j.state,
      });
    });
  });
  return docs;
}

/**
 * Search and filter jurisdictions and documents
 */
export function searchCoverage({ query = "", authority = "all", category = "all" } = {}) {
  const cleanQuery = query.trim().toLowerCase();
  
  return JURISDICTIONS.filter((jurisdiction) => {
    // Authority filter
    if (authority !== "all" && jurisdiction.type !== authority && jurisdiction.id !== authority) {
      return false;
    }

    // Category filter check against any doc in this jurisdiction
    if (category !== "all") {
      const hasCategoryDoc = jurisdiction.documents.some((doc) =>
        doc.category.toLowerCase().includes(category.toLowerCase()) ||
        doc.doc_type.toLowerCase().includes(category.toLowerCase())
      );
      if (!hasCategoryDoc) return false;
    }

    // Query search match against name, county, tags, doc titles, or notes
    if (cleanQuery) {
      const matchesJurisdiction =
        jurisdiction.name.toLowerCase().includes(cleanQuery) ||
        jurisdiction.fullName.toLowerCase().includes(cleanQuery) ||
        jurisdiction.county.toLowerCase().includes(cleanQuery) ||
        jurisdiction.highlights.some((h) => h.toLowerCase().includes(cleanQuery));

      const matchesDocs = jurisdiction.documents.some((doc) =>
        doc.title.toLowerCase().includes(cleanQuery) ||
        doc.notes.toLowerCase().includes(cleanQuery) ||
        doc.subject_tags.some((tag) => tag.toLowerCase().includes(cleanQuery))
      );

      if (!matchesJurisdiction && !matchesDocs) {
        return false;
      }
    }

    return true;
  });
}
